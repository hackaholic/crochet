import { act, renderHook } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import { useHeaderOffset } from './useHeaderOffset';
afterEach(() => { vi.unstubAllGlobals(); vi.restoreAllMocks(); document.documentElement.style.removeProperty('--storefront-header-height'); });
it('tracks wrapped header height, excludes the expanded menu and cleans up its observer', () => {
  let notify = () => {};
  const disconnect = vi.fn();
  vi.stubGlobal('ResizeObserver', class { constructor(callback: () => void) { notify = callback; } observe() {} disconnect = disconnect; });
  const header = document.createElement('div');
  const menu = document.createElement('div');
  let headerHeight = 123;
  let menuHeight = 0;
  vi.spyOn(header, 'getBoundingClientRect').mockImplementation(() => ({height:headerHeight}) as DOMRect);
  vi.spyOn(menu, 'getBoundingClientRect').mockImplementation(() => ({height:menuHeight}) as DOMRect);
  const headerRef = {current:header};
  const menuRef = {current:menu};
  const {unmount} = renderHook(() => useHeaderOffset(headerRef, menuRef));
  expect(document.documentElement.style.getPropertyValue('--storefront-header-height')).toBe('123px');
  headerHeight = 203; menuHeight = 80;
  act(() => notify());
  expect(document.documentElement.style.getPropertyValue('--storefront-header-height')).toBe('123px');
  headerHeight = 191; menuHeight = 80;
  act(() => notify());
  expect(document.documentElement.style.getPropertyValue('--storefront-header-height')).toBe('111px');
  unmount();
  expect(disconnect).toHaveBeenCalledOnce();
  expect(document.documentElement.style.getPropertyValue('--storefront-header-height')).toBe('');
});
it('uses window resizing when ResizeObserver is unavailable and preserves an existing token', () => {
  vi.stubGlobal('ResizeObserver', undefined);
  document.documentElement.style.setProperty('--storefront-header-height', '100px');
  const header = document.createElement('div');
  let height = 120;
  vi.spyOn(header, 'getBoundingClientRect').mockImplementation(() => ({height}) as DOMRect);
  const headerRef = {current:header}; const menuRef = {current:null};
  const {unmount} = renderHook(() => useHeaderOffset(headerRef, menuRef));
  height = 140;
  act(() => window.dispatchEvent(new Event('resize')));
  expect(document.documentElement.style.getPropertyValue('--storefront-header-height')).toBe('140px');
  unmount();
  expect(document.documentElement.style.getPropertyValue('--storefront-header-height')).toBe('100px');
});
